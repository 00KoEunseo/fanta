export function makeName(rng: Rng, race: RaceKey, sex: 'M' | 'F'): string {
  const n = N[race];
  const end = sex === 'M' ? n.endM : n.endF;
  return rng.pick(n.start) + rng.pick(n.mid) + rng.pick(end);
}

/** 이미 쓰인 이름을 피해 짓는다. 끝내 겹치면 음절을 하나 더 붙인다 */
export function uniqueName(rng: Rng, race: RaceKey, sex: 'M' | 'F', taken: (n: string) => boolean): string {
  let name = makeName(rng, race, sex);
  for (let i = 0; i < 15 && taken(name); i++) name = makeName(rng, race, sex);
  const n = N[race];
  for (let i = 0; i < 10 && taken(name); i++) {
    const end = sex === 'M' ? n.endM : n.endF;
    name = rng.pick(n.start) + (rng.pick(n.mid) || rng.pick(n.start)) + rng.pick(end);
  }
  return name;
}

export function uniquePlaceName(rng: Rng, race: RaceKey, taken: (n: string) => boolean): string {
  let name = makePlaceName(rng, race);
  for (let i = 0; i < 20 && taken(name); i++) name = makePlaceName(rng, race);
  if (taken(name)) name = `새 ${name}`;
  for (let i = 2; taken(name); i++) name = `${name.replace(/^새 /, '').replace(/ \d+$/, '')} ${i}`;
  return name;
}

export function makePlaceName(rng: Rng, race: RaceKey): string {
  const n = N[race];
  const a = rng.pick(n.place), b = rng.pick(n.placeEnd);
  // 형용사형(…은/…는/…의)으로 끝나면 띄어쓴다
  return /[은는의]$/.test(a) || a.length >= 3 ? `${a} ${b}`.replace(/ 의/, '의') : a + b;
}

export function makeClanName(rng: Rng, race: RaceKey): string {
  const n = N[race];
  return rng.pick(n.start) + rng.pick(n.endM);
}

